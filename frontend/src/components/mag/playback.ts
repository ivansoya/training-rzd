/** Ход времени при проигрывании ролика.
 *
 * Вынесено отдельно от хука сознательно: это чистый расчёт, от которого
 * зависит, какой кадр разметчик видит в каждый момент, и проверять его нужно
 * числами, а не браузером.
 */

/** На каком кадре ролик через `elapsed` миллисекунд после старта.
 *
 * Замедление и ускорение устроены по-разному, и это осознанно. Медленнее
 * единицы — просто медленнее идёт время, кадры показываются все. Быстрее —
 * ролик прореживается: 2× это «каждый второй кадр с обычной частотой», а не
 * «вдвое быстрее и как повезёт». Так быстрый просмотр выглядит одинаково ровно
 * на любой машине, а не превращается в рванину там, где декодер не поспевает.
 *
 * Кадр считается от прошедшего времени, а не как «следующий за показанным»:
 * тогда пропуск неразжатого кадра не превращается в замедление ролика. Искать
 * момент важнее, чем увидеть каждый кадр, и врать про время ради полноты
 * нельзя.
 */
/** Отсчёт проигрывания: с какого кадра и когда начали, и когда был прошлый шаг. */
export interface Clock {
  at: number;
  frame: number;
  last: number;
}

/**
 * Шаг часов проигрывания.
 *
 * Пока показан не тот кадр, который просили, время стоит: начало отсчёта
 * уезжает вперёд ровно на длительность ожидания, и прошедшее время не растёт.
 * Иначе получается пропажа куска ролика — полоса бежит, кадр замер, и что было
 * в пропущенном месте, никто не узнает.
 */
export function tickClock(clock: Clock, now: number, caughtUp: boolean): Clock {
  return {
    at: caughtUp ? clock.at : clock.at + (now - clock.last),
    frame: clock.frame,
    last: now,
  };
}

export function frameAt(
  from: number,
  elapsed: number,
  fps: number,
  speed: number,
  lastFrame: number
): number {
  const step = speed > 1 ? Math.round(speed) : 1;
  const rate = speed > 1 ? fps : fps * speed;
  const advanced = Math.floor((elapsed * rate) / 1000);
  return Math.min(lastFrame, from + advanced * step);
}
