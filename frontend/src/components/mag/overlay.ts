/** Арифметика слоя разметки: где на экране лежит объект и что у него показывать.
 *
 * Разметка рисуется **в экранных пикселях**, поверх кадра и вне его трансформа.
 * Так задумано, и это главное решение этого модуля.
 *
 * Прежде рамки и якоря лежали внутри масштабируемого слоя, а толщина
 * компенсировалась делением: `border: calc(2px / var(--z))`, якорь
 * `calc(10px / var(--z))`, а его положение — `calc(var(--hs) / -2)`, то есть
 * половина уже дробной величины. На зуме 12 это 0.167px рамки и 0.83px якоря
 * со смещением −0.417px: величины, которые браузер округляет до целых
 * устройственных пикселей, каждую грань по-своему. Отсюда мерцающая рамка и
 * якоря, съезжающие на пиксель. Проект уже дважды уходил из трансформа по
 * этой же причине — слой подписей («текст рассыпается») и слой полуавтомата
 * («точка вытягивалась в овал»); здесь переезд доводится до конца.
 *
 * В экранных пикселях делить не на что: 2 — это два пикселя на любом зуме.
 *
 * Второе решение: **что показывать, решает экранный размер объекта, а не
 * зум.** Восемь якорей по 10px вокруг объекта в 20px закрывают его целиком и
 * друг друга — и это одинаково верно при зуме 1 на мелком объекте и при зуме
 * 12 на крупном. Отсюда пороги ниже: они про то, во что можно попасть мышью.
 *
 * Модуль чистый, без DOM: проверяется числами в `overlay.test.ts`, набор идёт
 * в node.
 */

/** Прямоугольник кадра на экране — левый верхний угол и размеры в пикселях. */
export interface Rect {
  l: number;
  t: number;
  w: number;
  h: number;
}

/** Ниже этого объект не показывает якорей вовсе: попасть в них нельзя, а
 *  закрыть собой они успевают. Зумируют — и якоря появляются сами. */
export const ANCHORS_AT = 44;
/** Середины граней прибавляются, когда между углами есть куда их поставить. */
export const MIDS_AT = 90;
/** Вершины контура показываются, когда рёбра перестают сливаться в ободок. */
export const VERTEX_EDGE = 12;
/** Зона попадания — всегда столько, независимо от того, что нарисовано. */
export const HIT = 10;
/** Точка кадра → точка экрана. */
export function toScreen(
  x: number,
  y: number,
  width: number,
  height: number,
  rect: Rect
): [number, number] {
  return [rect.l + (x / width) * rect.w, rect.t + (y / height) * rect.h];
}

/** Экранных пикселей в одном пикселе кадра. Отдельно по осям: кадр вписан с
 *  сохранением пропорций, но полагаться на это молча — значит однажды получить
 *  вытянутую разметку и не понять почему. */
export function factors(
  width: number,
  height: number,
  rect: Rect
): [number, number] {
  return [width ? rect.w / width : 1, height ? rect.h / height : 1];
}

/** Экранное расстояние обратно в пиксели кадра.
 *
 * Нужно порогам попадания: «десять пикселей от курсора» — это всегда десять
 * экранных, а геометрия объекта живёт в пикселях кадра. По меньшему из
 * коэффициентов, чтобы зона попадания не оказалась уже обещанной ни по одной
 * из осей.
 */
export function toImageDistance(
  screen: number,
  width: number,
  height: number,
  rect: Rect
): number {
  const [kx, ky] = factors(width, height, rect);
  const k = Math.min(kx, ky);
  return k > 0 ? screen / k : screen;
}

/** Что показывать у выбранного объекта такого экранного размера. */
export interface Affordance {
  corners: boolean;
  mids: boolean;
}

export function affordance(screenW: number, screenH: number): Affordance {
  // По меньшей стороне: у плашки 300×20 середина вертикальной грани сидит
  // между двумя углами, до которых десять пикселей, — и все трое сливаются.
  const small = Math.min(screenW, screenH);
  return { corners: small >= ANCHORS_AT, mids: small >= MIDS_AT };
}

/** Показывать ли вершины контура: считаем по средней длине ребра на экране.
 *
 * По средней, а не по числу точек: контур из 64 точек вокруг крупного объекта
 * правится прекрасно, а из восьми вокруг мелкого — никак. Число точек про
 * это ничего не говорит, длина ребра говорит.
 */
export function showVertices(
  parts: [number, number][][],
  width: number,
  height: number,
  rect: Rect
): boolean {
  const [kx, ky] = factors(width, height, rect);
  let total = 0;
  let count = 0;
  for (const ring of parts) {
    for (let i = 0; i < ring.length; i++) {
      const a = ring[i];
      const b = ring[(i + 1) % ring.length];
      const dx = (a[0] - b[0]) * kx;
      const dy = (a[1] - b[1]) * ky;
      total += Math.hypot(dx, dy);
      count++;
    }
  }
  return count > 0 && total / count >= VERTEX_EDGE;
}

/** Ромб вокруг точки — знак поставленной человеком вершины.
 *
 * Тот же знак, что у ключевого кадра в дорожках треков: там ромб уже означает
 * «это положение поставил человек, а не посчитала машина». Разметчик читает
 * его без объяснений, потому что уже читал.
 */
export function diamond(cx: number, cy: number, r: number): string {
  return `M${cx} ${cy - r}L${cx + r} ${cy}L${cx} ${cy + r}L${cx - r} ${cy}Z`;
}
