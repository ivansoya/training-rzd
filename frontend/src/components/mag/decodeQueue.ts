/** Очередь разжатия и потолок ожидания. Вынесено ради проверки числами.
 *
 * Разжатие идёт по одному: два декодера на один перегон только мешают друг
 * другу. Отсюда очередь — и отсюда же её главная опасность. Задача, которая
 * не завершилась, держит не себя, а всех, кто выстроился за ней: редактор
 * замирает целиком, при живой сети, целых перегонах и без единой ошибки в
 * консоли. Именно так это и выглядело снаружи.
 *
 * Гарантия здесь одна и она проверяется тестами: сколько бы задача ни висела,
 * следующая дождётся своей очереди. Держится это на потолке времени, а не на
 * аккуратности вызывающего, потому что за потолком стоит чужой код —
 * `VideoDecoder` браузера, который после ошибки умеет молчать вечно.
 */

/** Разжатие застряло. Повторяемо: обычно хватает завести декодер заново. */
export class Stalled extends Error {}

/** Обещание с потолком по времени. Не дождались — считаем застрявшим.
 *
 * Работа при этом не отменяется: отменить чужое обещание нельзя. Она просто
 * перестаёт кого-либо держать, а её последствия вызывающий разгребает сам —
 * обычно выбрасывая декодер, к которому она относилась.
 */
export function withDeadline<T>(
  work: Promise<T>,
  ms: number,
  what: string,
  // Будильник передаётся, а не берётся из `window`: в браузере его там нет
  // только в воркере, а вот проверять это всё равно приходится без DOM.
  // Голые `setTimeout`/`clearTimeout` есть и там, и там.
  timers: {
    set: (fn: () => void, ms: number) => number;
    clear: (id: number) => void;
  } = {
    set: (fn, ms) => setTimeout(fn, ms) as unknown as number,
    clear: (id) => clearTimeout(id as unknown as ReturnType<typeof setTimeout>),
  }
): Promise<T> {
  return new Promise<T>((resolve, reject) => {
    const timer = timers.set(
      () => reject(new Stalled(`${what}: не дождались за ${ms / 1000} с.`)),
      ms
    );
    work.then(
      (value) => {
        timers.clear(timer);
        resolve(value);
      },
      (err) => {
        timers.clear(timer);
        reject(err);
      }
    );
  });
}

/** Очередь на одну дорожку: задачи идут по порядку и не мешают друг другу.
 *
 * Неудача одной не рвёт очередь — иначе первая же ошибка разжатия оставила бы
 * редактор без картинки навсегда.
 */
export function serialQueue() {
  let tail: Promise<unknown> = Promise.resolve();
  return function run<T>(task: () => Promise<T>): Promise<T> {
    const started = tail.then(task, task);
    tail = started.catch(() => undefined);
    return started;
  };
}
