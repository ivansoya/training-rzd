"""Контуры через маски: растеризовать, повернуть вместе с кадром, снять обратно.

Почему масками, а не точками. Точки едут быстрее и остаются теми же точками —
но что делать с вершиной, уехавшей за край кадра, albumentations не знает, и
подрезать кольцо по границе пришлось бы самим. Это ровно та геометрия, где
ошибиться легко и тихо: кольцо, обрезанное неверно, останется валидным
многоугольником и просто будет описывать не тот объект.

Маска решает это сама. Сечение краем — обрезка маски. Разрыв объекта на две
части — два внешних контура. Полное исчезновение — пустая маска, и объект
честно выпадает из разметки.

Цена названа вслух: кадр с контурами обрабатывается в несколько раз дольше
рамочного, а вершины после круга туда-обратно — уже не те же точки (растр
округляет до пикселя). Для обучения это безразлично, для «поправить контур
руками» — нет, но правят руками до сборки, а не после.
"""
from common.contours import polygons_from_mask

# Сколько объектов-контуров тянем через одно преобразование. Шестьдесят четыре
# маски кадра 4K по байту на пиксель — это полгигабайта на один образец;
# дальше не идём, а говорим об этом в отчёте сборки.
MAX_MASKS_PER_SAMPLE = 64
# До скольки точек упрощаем кольцо, снимая его обратно. Тот же порядок, что у
# полуавтомата: обводка не должна становиться подробнее оттого, что её
# покрутили.
POLY_POINTS = 96


def rasterize(parts, width, height):
    """Все кольца ОДНОГО объекта в одну маску.

    Одна маска на объект, а не одна на всё с номерами классов: два вагона
    внахлёст слились бы в один, и разметка потеряла бы объект, которого никто
    не удалял.
    """
    import cv2
    import numpy as np

    mask = np.zeros((height, width), dtype=np.uint8)
    rings = []
    for ring in parts or ():
        if len(ring) < 3:
            continue
        rings.append(np.array([[int(x), int(y)] for x, y in ring], np.int32))
    if rings:
        cv2.fillPoly(mask, rings, 1)
    return mask


def vectorize(mask, max_points=POLY_POINTS):
    """Обратно в кольца. Пустая маска — объект уехал из кадра целиком."""
    import numpy as np

    if mask is None:
        return []
    binary = (np.asarray(mask) > 0).astype("uint8")
    if not binary.any():
        return []
    return polygons_from_mask(binary, max_points)


def bounds_of(parts):
    """Охватывающая рамка всех колец объекта, в пикселях."""
    xs, ys = [], []
    for ring in parts or ():
        for x, y in ring:
            xs.append(float(x))
            ys.append(float(y))
    if not xs:
        return None
    return {"x": min(xs), "y": min(ys), "w": max(xs) - min(xs),
            "h": max(ys) - min(ys)}


def visible_share(before, after):
    """Какая доля объекта осталась в кадре.

    Считается по площади маски, а не по рамке: у длинного вагона, срезанного
    по диагонали, рамка почти не меняется, а объекта остаётся половина.
    """
    import numpy as np

    was = float(np.count_nonzero(before))
    if was <= 0:
        return 0.0
    return float(np.count_nonzero(after)) / was
