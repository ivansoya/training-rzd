"""Зёрна: как из одного числа получается воспроизводимая случайность.

Обещание «пересобрать набор точно так же» держится ровно на этом модуле.
Одно зерно у набора, всё остальное — производные от него, и ни одна из них не
зависит ни от порядка обхода, ни от числа потоков, ни от времени.

Ключевое: зерно образца считается от **кадра**, а не от счётчика. Счётчик
зависел бы от того, в каком порядке полосы разобрали кадры, и повтор сборки
на другой машине дал бы другие картинки при том же зерне.
"""
import hashlib

MASK64 = (1 << 64) - 1


def _u64(text: str) -> int:
    return int.from_bytes(
        hashlib.sha256(text.encode()).digest()[:8], "big"
    ) & MASK64


def frame_seed(set_seed, image_id) -> int:
    """Зерно кадра. Одинаково на любой машине и при любом порядке обхода."""
    return _u64(f"{set_seed}:{image_id}")


def node_seed(frame, path, copy_index=0) -> int:
    """Зерно одного применения узла к одному образцу.

    ``path`` — путь узла в развёрнутом плане (``g1/aug3``), поэтому один и тот
    же блок, вставленный дважды, крутит свои трансформы по-разному. Иначе обе
    копии дали бы одинаковую картинку, и умножение потеряло бы смысл.

    ``copy_index`` — номер копии у «Умножения» и номер ветки у
    последовательного разделителя.
    """
    return _u64(f"{frame}:{path}:{copy_index}")


def pick_branch(seed, weights) -> int:
    """Куда уйдёт образец на вероятностном разделителе.

    От зерна, а не от случайности процесса: один и тот же кадр обязан уходить
    в одну и ту же ветку при каждой сборке, иначе «то же зерно» ничего не
    значит.
    """
    total = sum(weights)
    if total <= 0:
        return 0
    # Берём дробную часть зерна как равномерное число в [0, 1).
    point = (seed & MASK64) / (MASK64 + 1) * total
    running = 0.0
    for i, w in enumerate(weights):
        running += w
        if point < running:
            return i
    return len(weights) - 1
