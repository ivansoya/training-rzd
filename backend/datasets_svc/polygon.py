def to_line(export_id, geometry, width, height):
    """Полигон → строка YOLO-seg ``class x1 y1 x2 y2 ...``, или None.

    None означает «от объекта после подрезки ничего не осталось» — ровно то же,
    что у бокса в ``_line``: вызывающий пропускает такую разметку молча, потому
    что кадр целиком отбраковывать из-за одного вырожденного объекта незачем.
    """
    if not width or not height:
        return None
    parts = clamp(parts_of(geometry), width, height)
    if not parts:
        return None
    ring = merge(parts)
    if len(ring) < MIN_POINTS:
        return None
    coords = []
    for x, y in ring:
        coords.append(f"{x / width:.6f}")
        coords.append(f"{y / height:.6f}")
    return f"{export_id} " + " ".join(coords) + "\n"


def line_kind(fields):
    """Что за строка YOLO по числу её полей: ``"bbox"``, ``"polygon"`` или None.

    Знание о форме строки живёт рядом с её записью, а не у читателя архива:
    писать и разбирать один формат в двух файлах — верный способ развести их.

    Пять полей — бокс, и спорить не о чем: так их писали все годы до появления
    контуров, и двухточечного контура формат не знает. Контур — нечётное число
    полей от семи: класс плюс пары координат, не меньше трёх точек.
    """
    if fields == 5:
        return "bbox"
    if fields >= 1 + MIN_POINTS * 2 and fields % 2 == 1:
        return "polygon"
    return None


def from_line(coords, width, height):
    """Нормализованные пары из строки YOLO-seg → кольцо в пикселях.

    Обратная сторона ``to_line``, и проверяется она кругом: выгрузили, втянули,
    сравнили. Одна часть на входе — одна на выходе: перемычка при чтении не
    распознаётся и не разбирается обратно, она уже часть контура.
    """
    if len(coords) < MIN_POINTS * 2 or len(coords) % 2:
        return None
    ring = [(coords[i] * width, coords[i + 1] * height)
            for i in range(0, len(coords), 2)]
    return _clean_ring(ring)
