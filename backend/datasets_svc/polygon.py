"""Геометрия полигональной разметки: части объекта, их границы и выгрузка.

Объект-полигон хранится одной строкой ``annotations`` с ``ann_type="polygon"``
и геометрией ``{"parts": [[[x, y], ...], ...]}`` — списком колец в пикселях
изображения. Частей несколько, потому что объект бывает разорван: вагон за
стойкой виден двумя половинами, и обводка обязана показывать ровно то же,
что охватывает рамка. SAM2 отдаёт куски маски именно так (``RETR_EXTERNAL``,
до ``MAX_PARTS`` штук), и хранилище повторяет эту форму, а не спрямляет её.

Дырок здесь нет. ``parts`` — разъединённые куски, а не кольца с отверстиями:
модель их не отдаёт, а формат, в который мы выгружаем, отверстий не знает.

Модуль намеренно чистый: ни моделей, ни БД, ни numpy. Такую арифметику
проверяют числами (``tests/unit/test_polygon.py``), а не глазами по картинке.
"""

# Меньше трёх точек — не фигура, а отрезок. Правило одно на клиент и сервер:
# замкнуть контур из двух точек редактор не даёт, и принять такой снаружи
# было бы дырой в том же правиле.
MIN_POINTS = 3


def parts_of(geometry):
    """Кольца объекта из его геометрии — всегда список списков пар чисел.

    Терпимо к форме входа нарочно: геометрия приходит из JSON-поля, где
    когда-то мог оказаться и одиночный контур ``{"points": [...]}``. Отдельная
    ветка дешевле, чем миграция ради формы, которую никто не писал.
    """
    if not isinstance(geometry, dict):
        return []
    raw = geometry.get("parts")
    if raw is None:
        single = geometry.get("points")
        raw = [single] if single else []
    out = []
    for ring in raw or []:
        clean = _clean_ring(ring)
        if clean is not None:
            out.append(clean)
    return out


def _clean_ring(ring):
    """Кольцо в виде списка пар чисел, или None, если это не кольцо.

    Совпадающие соседи убираются здесь, а не при рисовании: точка, поставленная
    дважды подряд, ломает счёт площади и вырождает ребро, по которому потом
    ищут вставку новой вершины.
    """
    if not isinstance(ring, (list, tuple)):
        return None
    pts = []
    for p in ring:
        try:
            if isinstance(p, dict):
                x, y = float(p["x"]), float(p["y"])
            else:
                x, y = float(p[0]), float(p[1])
        except (KeyError, IndexError, TypeError, ValueError):
            return None
        if pts and _same(pts[-1], (x, y)):
            continue
        pts.append((x, y))
    # Замыкающая точка, повторяющая первую, — способ записи, а не вершина.
    while len(pts) > 1 and _same(pts[0], pts[-1]):
        pts.pop()
    return pts if len(pts) >= MIN_POINTS else None


def _same(a, b):
    return abs(a[0] - b[0]) < 1e-9 and abs(a[1] - b[1]) < 1e-9


def signed_area(ring):
    """Площадь кольца по формуле шнурков, со знаком.

    Знак — это направление обхода, и он тут не мелочь: у склейки от него
    зависит, сложатся площади частей или вычтутся.
    """
    total = 0.0
    n = len(ring)
    for i in range(n):
        x1, y1 = ring[i]
        x2, y2 = ring[(i + 1) % n]
        total += x1 * y2 - x2 * y1
    return total / 2.0


def area(ring):
    """Площадь кольца. Направление обхода разметчика не касается."""
    return abs(signed_area(ring))


def bounds(parts):
    """Охватывающая рамка всех частей в пикселях, в тех же ключах, что у бокса.

    Нужна в двух местах: выгрузка боксами сводит к ней полигон, а редактор
    ставит по ней подпись класса. Считается по всем частям сразу — рамка вокруг
    одной половины разорванного объекта была бы неправдой.
    """
    xs = [p[0] for ring in parts for p in ring]
    ys = [p[1] for ring in parts for p in ring]
    if not xs:
        return None
    x0, x1 = min(xs), max(xs)
    y0, y1 = min(ys), max(ys)
    return {"x": round(x0, 2), "y": round(y0, 2),
            "w": round(x1 - x0, 2), "h": round(y1 - y0, 2)}


def clamp(parts, width, height):
    """Точки — внутрь кадра, вырожденные после подрезки кольца — прочь.

    Подрезаем точки, а не отбрасываем кольцо целиком: объект у края кадра
    размечают ровно так — ведя контур по самой границе, и доли пикселя наружу
    здесь обычное дело, а не ошибка разметчика.
    """
    out = []
    for ring in parts:
        cut = [(min(max(x, 0.0), float(width)), min(max(y, 0.0), float(height)))
               for x, y in ring]
        cut = _clean_ring(cut)
        # Кольцо, легшее в линию на границе кадра, площади не имеет и в
        # обучение принесёт только строку мусора.
        if cut is not None and area(cut) > 0.0:
            out.append(cut)
    return out


