# Склейка перемычкой
# --------------------------------------------------------------------------- #
def merge(parts):
    """Несколько колец — в одно, соединив их перемычками нулевой ширины.

    Формат YOLO-seg знает **один** контур на объект: строка — это ``class`` и
    пары координат подряд. Объекта из двух кусков он выразить не может, и
    выбор здесь между «склеить» и «разложить на два объекта». Разложить нельзя:
    один вагон, заслонённый стойкой, стал бы двумя вагонами, и модель училась
    бы считать неправильно. Поэтому склеиваем — так же поступает и сам
    ultralytics, приводя многочастную сегментацию COCO к своему формату.

    Перемычка проходится дважды, туда и обратно, и ширины не имеет: при
    растеризации маски она не даёт площади. Именно поэтому склейка честнее,
    чем кажется — она меняет запись, а не фигуру.

    Соединяем жадно: к накопителю каждый раз прирастает то кольцо, до которого
    ближе всего. Разбор ultralytics идёт по цепочке «сосед к соседу» и на
    кольцах, разбросанных по кадру, тянет перемычку через весь объект; жадный
    выбор такой же дешёвый, но не создаёт длинных стежков поперёк картинки.

    Цена названа: поиск ближайшей пары — перебор всех пар точек, O(n·m).
    На типичном объекте (2-3 части по 64 точки после ``polygon_points``) это
    несколько тысяч сравнений; на пределе SAM2 (24 части) — единицы миллионов
    за объект, и это единственное место выгрузки, где такое возможно.
    """
    rings = [list(r) for r in parts if r]
    if not rings:
        return []
    if len(rings) == 1:
        return list(rings[0])

    # Все кольца обходим в одну сторону. Иначе склейка встречных обходов
    # вычитает площадь вместо того, чтобы складывать: заливка по правилу
    # ненулевого числа оборотов выбьет в объекте дыру ровно там, где лежит
    # вторая часть. Куски SAM2 приходят из cv2 согласованными, но полигон
    # может быть и нарисован рукой — а рука ходит в обе стороны.
    rings = [r if signed_area(r) >= 0 else r[::-1] for r in rings]

    # Начинаем с самого крупного куска: он и есть объект, остальное — довесок.
    rings.sort(key=area, reverse=True)
    acc = rings.pop(0)
    while rings:
        best = None
        for k, ring in enumerate(rings):
            i, j, dist = _closest_pair(acc, ring)
            if best is None or dist < best[0]:
                best = (dist, k, i, j)
        _, k, i, j = best
        ring = rings.pop(k)
        # Доходим по накопителю до точки i, перепрыгиваем в точку j кольца,
        # обходим его целиком и возвращаемся в ту же i. Обе перемычки лежат
        # одна на другой — отсюда нулевая ширина.
        acc = acc[:i + 1] + ring[j:] + ring[:j + 1] + acc[i:]
    return acc


def _closest_pair(a, b):
    """Индексы ближайших друг к другу точек двух колец и квадрат расстояния.

    Квадрат, а не расстояние: корень здесь ничего не решает, а берётся он
    столько же раз, сколько сравнений.
    """
    best_i = best_j = 0
    best = None
    for i, (ax, ay) in enumerate(a):
        for j, (bx, by) in enumerate(b):
            d = (ax - bx) ** 2 + (ay - by) ** 2
            if best is None or d < best:
                best, best_i, best_j = d, i, j
    return best_i, best_j, best


