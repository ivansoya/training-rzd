"""Пересчёт координат полуавтомата — числами, без модели и без картинки.

Проверяется то, из-за чего SAM2 в разметке видео обводил не то, что просили:
редактор считает в пикселях источника, а кадр модели приходил ступенью
качества, то есть мельче. Пока обе стороны молчали о своих размерах, точка из
1920×1080 попадала в 1280×720 на две трети пути к цели.
"""
import pytest

from autolabel_svc.space import factors, to_frame, to_space

# Ролик 1920×1080, показанный ступенью 720p: ровно тот случай, что ломался.
SPACE = {"w": 1920, "h": 1080}
FRAME = (1280, 720)


def test_совпадающий_размер_ничего_не_меняет():
    """Обычный случай после починки: кадр распакован в размерах источника.
    Пересчёт обязан быть тождеством, а не «почти тождеством» с дрожанием в
    сотых — иначе бокс поедет от одного пересохранения к другому."""
    kx, ky = factors(SPACE, 1920, 1080)
    assert (kx, ky) == (1.0, 1.0)
    prompts = {"points": [{"x": 640.5, "y": 360.25, "label": 1}]}
    assert to_frame(prompts, kx, ky) is prompts
    shape = {"box": {"x": 10, "y": 20, "w": 30, "h": 40}}
    assert to_space(shape, kx, ky, SPACE) is shape


def test_точка_попадает_в_ту_же_долю_кадра():
    kx, ky = factors(SPACE, *FRAME)
    out = to_frame({"points": [{"x": 1440, "y": 810, "label": 1}]}, kx, ky)
    assert out["points"][0] == {"x": 960.0, "y": 540.0, "label": 1}


def test_рамка_подсказки_едет_целиком():
    kx, ky = factors(SPACE, *FRAME)
    out = to_frame({"box": {"x": 960, "y": 540, "w": 480, "h": 270}}, kx, ky)
    assert out["box"] == {"x": 640.0, "y": 360.0, "w": 320.0, "h": 180.0}


def test_исходный_запрос_не_портится():
    """Запрос клиента — не наша собственность: правка на месте однажды ушла бы
    обратно в ответе."""
    prompts = {"points": [{"x": 1440, "y": 810, "label": 1}]}
    to_frame(prompts, *factors(SPACE, *FRAME))
    assert prompts["points"][0]["x"] == 1440


def test_ответ_возвращается_в_пикселях_разметчика():
    kx, ky = factors(SPACE, *FRAME)
    shape = to_space(
        {"box": {"x": 640, "y": 360, "w": 320, "h": 180}, "score": 0.9}, kx, ky, SPACE
    )
    assert shape["box"] == {"x": 960.0, "y": 540.0, "w": 480.0, "h": 270.0}
    assert shape["score"] == 0.9


def test_обводка_едет_вместе_с_рамкой():
    """Для сегментации полигон и есть результат, а рамка — его тень. Разъехавшись,
    они противоречили бы друг другу на одном экране."""
    kx, ky = factors(SPACE, *FRAME)
    shape = to_space(
        {"box": {"x": 0, "y": 0, "w": 640, "h": 360},
         "polygons": [[[0, 0], [640, 0], [640, 360]]]},
        kx, ky, SPACE,
    )
    assert shape["polygons"] == [[[0.0, 0.0], [960.0, 0.0], [960.0, 540.0]]]


def test_рамка_не_вылезает_за_кадр():
    """Деление даёт дробные края, и на границе они уходят за картинку на доли
    пикселя. Хранилищу разметки этого хватает, чтобы обрезать бокс по-своему."""
    kx, ky = factors(SPACE, *FRAME)
    shape = to_space({"box": {"x": 1279, "y": 719, "w": 1, "h": 1}}, kx, ky, SPACE)
    box = shape["box"]
    assert box["x"] + box["w"] <= SPACE["w"]
    assert box["y"] + box["h"] <= SPACE["h"]


@pytest.mark.parametrize("space", [None, {}, {"w": 0, "h": 1080}, {"w": "нет", "h": None}])
def test_невнятное_пространство_не_роняет_разметку(space):
    """Клиент старой версии не пришлёт размера вовсе. Это не повод отказывать:
    считаем, что он говорит в пикселях кадра, — так и было до этой правки."""
    assert factors(space, *FRAME) == (1.0, 1.0)
