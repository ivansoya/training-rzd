"""Геометрия полигонов — без базы, без сервера, без картинок.

Здесь проверяется то, что решает, каким объект уедет в датасет. Главная
проверка — склейка перемычкой: она меняет запись фигуры, и надо убедиться
числами, что фигуру она при этом не меняет.
"""
import pytest

from datasets_svc.polygon import (
    MIN_POINTS,
    area,
    bounds,
    clamp,
    from_line,
    line_kind,
    merge,
    parts_of,
    signed_area,
    to_line,
)


def square(x, y, side, ccw=True):
    """Квадрат со стороной side. По часовой или против — по просьбе."""
    pts = [(x, y), (x + side, y), (x + side, y + side), (x, y + side)]
    return pts if ccw else pts[::-1]


# --------------------------------------------------------------------------- #
# Разбор геометрии
# --------------------------------------------------------------------------- #
def test_части_читаются_из_parts():
    parts = parts_of({"parts": [square(0, 0, 10), square(50, 0, 10)]})
    assert len(parts) == 2
    assert parts[0][0] == (0.0, 0.0)


def test_одиночный_контур_старой_формы_тоже_читается():
    parts = parts_of({"points": square(0, 0, 10)})
    assert len(parts) == 1


def test_замыкающая_точка_не_становится_вершиной():
    ring = square(0, 0, 10) + [(0, 0)]
    parts = parts_of({"parts": [ring]})
    assert len(parts[0]) == 4


def test_повтор_соседней_точки_убирается():
    ring = [(0, 0), (0, 0), (10, 0), (10, 10)]
    parts = parts_of({"parts": [ring]})
    assert len(parts[0]) == 3


def test_кольцо_короче_трёх_точек_отброшено():
    assert parts_of({"parts": [[(0, 0), (10, 10)]]}) == []
    assert MIN_POINTS == 3


def test_мусор_вместо_геометрии_не_роняет_разбор():
    assert parts_of(None) == []
    assert parts_of({"parts": "не список"}) == []
    assert parts_of({"parts": [[{"нет": "координат"}]]}) == []


# --------------------------------------------------------------------------- #
# Площадь и границы
# --------------------------------------------------------------------------- #
def test_площадь_квадрата():
    assert area(square(0, 0, 10)) == pytest.approx(100.0)


def test_направление_обхода_видно_по_знаку():
    assert signed_area(square(0, 0, 10)) > 0
    assert signed_area(square(0, 0, 10, ccw=False)) < 0
    assert area(square(0, 0, 10, ccw=False)) == pytest.approx(100.0)


def test_рамка_охватывает_все_части():
    b = bounds([square(0, 0, 10), square(50, 20, 10)])
    assert b == {"x": 0.0, "y": 0.0, "w": 60.0, "h": 30.0}


# --------------------------------------------------------------------------- #
# Подрезка по кадру
# --------------------------------------------------------------------------- #
def test_точки_за_краем_прижимаются_к_кадру():
    parts = clamp([[(-5, -5), (50, 0), (50, 50)]], 40, 40)
    assert parts[0][0] == (0.0, 0.0)
    assert max(x for x, _ in parts[0]) == 40.0


def test_кольцо_легшее_в_линию_отброшено():
    # Целиком за левым краем: после подрезки все точки на x = 0.
    assert clamp([[(-30, 0), (-20, 10), (-10, 20)]], 100, 100) == []


# --------------------------------------------------------------------------- #
# Склейка перемычкой — главная проверка
# --------------------------------------------------------------------------- #
def test_одна_часть_склейки_не_требует():
    ring = square(0, 0, 10)
    assert merge([ring]) == ring


def test_два_квадрата_склеиваются_в_одно_кольцо():
    ring = merge([square(0, 0, 10), square(50, 0, 10)])
    assert len(ring) >= 8


def test_площадь_склеенного_равна_сумме_площадей():
    """Перемычка проходится туда и обратно и площади не даёт.

    Это и есть довод, ради которого склейку выбрали вместо разложения на два
    объекта: меняется запись, а не фигура. Проверяем шнурками — они по
    перемычке дают +A и −A, и те сокращаются.
    """
    parts = [square(0, 0, 10), square(50, 0, 20)]
    assert area(merge(parts)) == pytest.approx(100.0 + 400.0)


def test_встречный_обход_не_выбивает_дыру():
    """Кольца с разным направлением обхода обязаны сложиться, а не вычесться.

    Без выравнивания ориентации здесь получилось бы 400 − 100 = 300, и в маске
    на месте меньшего квадрата оказалась бы дыра.
    """
    parts = [square(0, 0, 10, ccw=False), square(50, 0, 20, ccw=True)]
    assert area(merge(parts)) == pytest.approx(500.0)


def test_склейка_не_теряет_ни_одной_точки():
    a, b = square(0, 0, 10), square(50, 0, 10)
    ring = merge([a, b])
    for p in a + b:
        assert p in ring


def test_три_части_складываются_все():
    parts = [square(0, 0, 10), square(50, 0, 10), square(100, 0, 10)]
    assert area(merge(parts)) == pytest.approx(300.0)


# --------------------------------------------------------------------------- #
# Строки YOLO
# --------------------------------------------------------------------------- #
def test_строка_начинается_с_класса_и_несёт_пары():
    line = to_line(3, {"parts": [square(0, 0, 50)]}, 100, 100)
    fields = line.split()
    assert fields[0] == "3"
    assert (len(fields) - 1) % 2 == 0
    assert len(fields) - 1 == 8


def test_координаты_строки_нормализованы():
    line = to_line(0, {"parts": [square(0, 0, 50)]}, 100, 200)
    vals = [float(v) for v in line.split()[1:]]
    assert all(0.0 <= v <= 1.0 for v in vals)
    # Квадрат 50×50 в кадре 100×200: по x это половина, по y четверть.
    assert max(vals[0::2]) == pytest.approx(0.5)
    assert max(vals[1::2]) == pytest.approx(0.25)


def test_вырожденный_объект_не_даёт_строки():
    assert to_line(0, {"parts": []}, 100, 100) is None
    assert to_line(0, {"parts": [[(-9, 0), (-8, 5), (-7, 9)]]}, 100, 100) is None


def test_круг_выгрузили_втянули_совпало():
    """Выгрузка и импорт — обратные друг другу. Проверяется вместе, иначе
    расхождение вылезет только на чужом архиве и уже как порча данных."""
    ring = [(10.0, 20.0), (90.0, 25.0), (70.0, 80.0), (15.0, 60.0)]
    line = to_line(2, {"parts": [ring]}, 200, 100)
    coords = [float(v) for v in line.split()[1:]]
    back = from_line(coords, 200, 100)
    assert len(back) == len(ring)
    for got, want in zip(back, ring):
        assert got[0] == pytest.approx(want[0], abs=0.01)
        assert got[1] == pytest.approx(want[1], abs=0.01)


def test_нечётное_число_координат_не_читается():
    assert from_line([0.1, 0.2, 0.3], 100, 100) is None


def test_слишком_короткая_строка_не_читается():
    assert from_line([0.1, 0.2, 0.3, 0.4], 100, 100) is None


