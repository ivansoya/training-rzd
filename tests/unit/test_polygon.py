def test_пять_полей_это_всегда_бокс():
    """Так их писали все годы до появления контуров, и двухточечного контура
    формат не знает — спорить не о чем."""
    assert line_kind(5) == "bbox"


def test_нечётное_от_семи_это_контур():
    assert line_kind(7) == "polygon"
    assert line_kind(9) == "polygon"
    assert line_kind(129) == "polygon"


def test_чётное_число_полей_не_строка():
    assert line_kind(8) is None
    assert line_kind(6) is None


def test_слишком_короткая_строка_не_строка():
    assert line_kind(3) is None
    assert line_kind(4) is None


def test_запись_и_разбор_согласованы():
    """Что записали, то и должно опознаться: иначе свой же архив не втянется."""
    line = to_line(0, {"parts": [square(0, 0, 50)]}, 100, 100)
    assert line_kind(len(line.split())) == "polygon"
